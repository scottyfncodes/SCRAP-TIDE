"""Outline the SCRAP TIDE wordmark lettering into SVG path data (src/ui/wordmarkPath.ts).

The wordmark used to be live SVG <text> pinned to its width with textLength + lengthAdjust="spacingAndGlyphs".
Safari does not apply that reliably (the lettering came out at its natural, wider width: first as brown slabs
beside the face, then cut off at the S and the E), so the letters are now fixed outlines that render the same in
every browser and need no font to load.

Layout matches what the <text> was meant to be: Saira Stencil One at 128 px, shaped with HarfBuzz (kerning
included), the run's advance stretched horizontally to span x 12..628 of the 640 x 150 viewBox, baseline y 124.

    python3 -m pip install fonttools brotli uharfbuzz
    python3 scripts/wordmark-outline.py            (rewrites src/ui/wordmarkPath.ts)
"""
import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'public/fonts/saira-stencil-one-400-latin.woff2'
OUT = ROOT / 'src/ui/wordmarkPath.ts'
TEXT, SIZE, X0, WIDTH, BASE = 'SCRAP TIDE', 128, 12, 616, 124

font = TTFont(FONT)
buf = io.BytesIO()
font.flavor = None
font.save(buf)
data = buf.getvalue()
font = TTFont(io.BytesIO(data))
upm = font['head'].unitsPerEm
glyphs = font.getGlyphSet()

hbfont = hb.Font(hb.Face(data))
b = hb.Buffer()
b.add_str(TEXT)
b.guess_segment_properties()
hb.shape(hbfont, b, {'kern': True, 'liga': True})
order = font.getGlyphOrder()

total = sum(p.x_advance for p in b.glyph_positions)
s = SIZE / upm
sx = WIDTH / (total * s)  # the horizontal stretch textLength applied

pen = SVGPathPen(glyphs, ntos=lambda v: f'{v:.1f}'.rstrip('0').rstrip('.'))
x = 0
for info, pos in zip(b.glyph_infos, b.glyph_positions):
    name = order[info.codepoint]
    tx = X0 + (x + pos.x_offset) * s * sx
    ty = BASE - pos.y_offset * s
    glyphs[name].draw(TransformPen(pen, (s * sx, 0, 0, -s, tx, ty)))
    x += pos.x_advance

OUT.write_text(
    '// Generated by scripts/wordmark-outline.py: the SCRAP TIDE lettering (Saira Stencil One, 128 px, stretched to\n'
    '// x 12..628, baseline y 124 of a 640 x 150 viewBox) as outlines. Do not edit by hand.\n'
    f"export const WORDMARK_D = '{pen.getCommands()}';\n"
)
print(f'{OUT.relative_to(ROOT)}: {len(pen.getCommands())} chars, stretch {sx:.3f}')
